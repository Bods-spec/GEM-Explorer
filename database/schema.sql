-- GEM Explorer AI · Supabase PostgreSQL schema (NOT MySQL).
-- Paste entire script in Supabase Dashboard -> SQL Editor -> Run.
-- Safe to rerun in a fresh project; does not delete existing data.

-- Supabase Auth (auth.users) manages passwords. Never store password_hash here.
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'visitor' CHECK (role IN ('visitor', 'admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.museum_sections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  title_en text NOT NULL,
  title_ar text NOT NULL,
  source_url text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.artifacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id bigint REFERENCES public.museum_sections(id) ON DELETE SET NULL,
  title_en text NOT NULL,
  title_ar text NOT NULL,
  era text,
  description_en text,
  description_ar text,
  image_url text,
  image_credit text,
  source_url text,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS artifacts_section_idx ON public.artifacts(section_id);
CREATE INDEX IF NOT EXISTS artifacts_published_idx ON public.artifacts(is_published);

CREATE TABLE IF NOT EXISTS public.favorites (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  artifact_id bigint NOT NULL REFERENCES public.artifacts(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, artifact_id)
);

-- Educational visit plan only: not a real museum ticket, reservation, or payment.
CREATE TABLE IF NOT EXISTS public.bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  visit_date date NOT NULL,
  ticket_count integer NOT NULL CHECK (ticket_count BETWEEN 1 AND 10),
  status text NOT NULL DEFAULT 'demo_pending'
    CHECK (status IN ('demo_pending', 'demo_cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS bookings_user_date_idx ON public.bookings(user_id, visit_date);

-- Create visitor profile on signup; role can never be set from user metadata.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  INSERT INTO public.profiles(id, full_name, role)
  VALUES (NEW.id, LEFT(COALESCE(NEW.raw_user_meta_data ->> 'full_name', ''), 120), 'visitor')
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;

-- Enable Row Level Security on ALL exposed tables.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.museum_sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.artifacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- Explicit minimal table grants (SQL Editor can have default broad grants).
REVOKE ALL ON public.profiles, public.museum_sections, public.artifacts,
  public.favorites, public.bookings FROM anon, authenticated;
GRANT SELECT ON public.museum_sections, public.artifacts TO anon, authenticated;
GRANT SELECT ON public.profiles TO authenticated;
GRANT SELECT, INSERT, DELETE ON public.favorites TO authenticated;
GRANT SELECT, INSERT ON public.bookings TO authenticated;
-- Node.js server secret key uses service_role, which BYPASSES RLS.
GRANT ALL ON public.profiles, public.museum_sections, public.artifacts,
  public.favorites, public.bookings TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- Public collection is read-only and limited to PUBLISHED artifacts.
DROP POLICY IF EXISTS "Public can view museum sections" ON public.museum_sections;
CREATE POLICY "Public can view museum sections" ON public.museum_sections
FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Public can view published artifacts" ON public.artifacts;
CREATE POLICY "Public can view published artifacts" ON public.artifacts
FOR SELECT TO anon, authenticated USING (is_published = true);

-- A user can read only their own profile; admin role is never user-editable.
DROP POLICY IF EXISTS "Visitor can view own profile" ON public.profiles;
CREATE POLICY "Visitor can view own profile" ON public.profiles
FOR SELECT TO authenticated USING ((SELECT auth.uid()) = id);

DROP POLICY IF EXISTS "Visitor can read own favorites" ON public.favorites;
CREATE POLICY "Visitor can read own favorites" ON public.favorites
FOR SELECT TO authenticated USING ((SELECT auth.uid()) = user_id);
DROP POLICY IF EXISTS "Visitor can add own favorites" ON public.favorites;
CREATE POLICY "Visitor can add own favorites" ON public.favorites
FOR INSERT TO authenticated WITH CHECK ((SELECT auth.uid()) = user_id);
DROP POLICY IF EXISTS "Visitor can remove own favorites" ON public.favorites;
CREATE POLICY "Visitor can remove own favorites" ON public.favorites
FOR DELETE TO authenticated USING ((SELECT auth.uid()) = user_id);

DROP POLICY IF EXISTS "Visitor can view own demo bookings" ON public.bookings;
CREATE POLICY "Visitor can view own demo bookings" ON public.bookings
FOR SELECT TO authenticated USING ((SELECT auth.uid()) = user_id);
DROP POLICY IF EXISTS "Visitor can create own demo booking" ON public.bookings;
CREATE POLICY "Visitor can create own demo booking" ON public.bookings
FOR INSERT TO authenticated WITH CHECK (
  (SELECT auth.uid()) = user_id AND status = 'demo_pending'
);

